// Every walkable world has a hand-plotted map here: each notable thing in the
// world (a structure, a person/figure, an EPK screen, a game, a landmark prop)
// is an item with its real world-space [x, z] position, so the encyclopedia
// map matches what you actually walk past. codex.js renders these as labeled
