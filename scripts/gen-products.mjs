// Generate src/data/products.js — the baked 12matt3r store catalogue — from the
// committed Shopify export (scripts/data/shopify-products.json).
//
// The export itself is a trimmed snapshot of the live storefront:
//   curl 'https://zr1a7y-8x.myshopify.com/collections/all/products.json?limit=250'
// re-trimmed into scripts/data/shopify-products.json (title, handle, type, tags,
// price range, sizes/colors, up to 3 cdn.shopify.com image URLs, variants, a
// plain-text description excerpt). Baking it means every visitor gets the full
// catalogue with no live API call. Product pages open on doesntmatter.store.
//
// Regenerate after refreshing the snapshot:  node scripts/gen-products.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const STORE_URL = 'https://www.doesntmatter.store';
const src = JSON.parse(readFileSync('scripts/data/shopify-products.json', 'utf8'));

// Group into shelves by product type, tees first (the bulk of the drop).
const TYPE_ORDER = ['T-Shirt', 'Hoodie', 'Shorts'];
const typeRank = (t) => { const i = TYPE_ORDER.indexOf(t); return i === -1 ? 99 : i; };

const products = src
  .filter((p) => Array.isArray(p.images) && p.images.length > 0)   // need at least a front image to display
  .map((p) => ({
    id: p.id,
    title: p.title,
    type: p.type,
    tags: p.tags ?? [],
    priceMin: p.priceMin,
    priceMax: p.priceMax,
    sizes: p.sizes ?? [],
    colors: p.colors ?? [],
    images: p.images,
    variants: p.variants ?? [],
    desc: p.desc ?? '',
    url: `${STORE_URL}/products/${p.handle}`,
  }))
  .sort((a, b) => typeRank(a.type) - typeRank(b.type) || a.title.localeCompare(b.title));

const types = [...new Set(products.map((p) => p.type))];

const banner = `// AUTO-GENERATED by scripts/gen-products.mjs — do not edit by hand.
// Source: scripts/data/shopify-products.json (trimmed Shopify export).
// The live 12matt3r store: ${STORE_URL}  (${products.length} products)\n`;

const body =
  banner +
  `export const STORE_URL = ${JSON.stringify(STORE_URL)};\n` +
  `export const PRODUCT_TYPES = ${JSON.stringify(types)};\n` +
  `export const PRODUCTS = ${JSON.stringify(products, null, 0)};\n`;

writeFileSync('src/data/products.js', body);
console.log(`wrote src/data/products.js — ${products.length} products, types: ${types.join(', ')}`);
