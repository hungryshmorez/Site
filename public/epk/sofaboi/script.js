function extractArtistName(url) {
    const match = url.match(/https?:\/\/([^.]+)\.bandcamp\.com/);
    return match ? match[1] : url;
}

function createArtistCard(url) {
    const artistName = extractArtistName(url);
    const card = document.createElement('a');
    card.href = url;
    card.target = '_blank';
    card.className = 'artist-card';
    card.innerHTML = `
        <div class="artist-name">${artistName}</div>
        <div class="artist-url">${url}</div>
    `;
    return card;
}

function renderArtists(artists) {
    const grid = document.getElementById('artistGrid');
    grid.innerHTML = '';
    
    artists.forEach(url => {
        const card = createArtistCard(url);
        grid.appendChild(card);
    });
    
    document.getElementById('totalCount').textContent = artists.length;
}

